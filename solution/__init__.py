"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

import os

from .swiglu import patch_qwen2_mlp
from .rmsnorm import patch_qwen2_rmsnorm
from .fused_cross_entropy import patch_cross_entropy
from .rope import patch_qwen2_rope
from .residual_add import patch_qwen2_decoder_layer
from .fused_lora import patch_lora

# Debug-only bisection switch, OFF by default: SOUP_DISABLE_KERNELS=rope,lora (comma-separated)
# skips those patches so a jury/team run can isolate which kernel a regression comes from without
# a new commit per combination. Unset (the jury's and the default Kaggle run's case) applies every
# patch below exactly as before -- this changes nothing about the submitted behavior by default.
_OPTIONAL_PATCHES = {
    "rmsnorm": patch_qwen2_rmsnorm,       # Dev
    "cross_entropy": patch_cross_entropy,  # ML
    "rope": patch_qwen2_rope,             # Dev
    "residual_add": patch_qwen2_decoder_layer,  # Dev
    "lora": patch_lora,                   # ML
}


def apply():
    patch_qwen2_mlp()  # the example: works out of the box, does not count as your own kernel
    disabled = {name for name in os.environ.get("SOUP_DISABLE_KERNELS", "").split(",") if name}
    unknown = disabled - set(_OPTIONAL_PATCHES)
    if unknown:
        raise ValueError(f"SOUP_DISABLE_KERNELS: unknown kernel name(s) {sorted(unknown)}, "
                         f"expected a subset of {sorted(_OPTIONAL_PATCHES)}")
    for name, patch_fn in _OPTIONAL_PATCHES.items():
        if name not in disabled:
            patch_fn()
    if disabled:
        print(f"[solution] SOUP_DISABLE_KERNELS active, skipped: {sorted(disabled)}")

    # Debug-only, OFF by default: SOUP_DEBUG_ANOMALY=1 turns on
    # torch.autograd.set_detect_anomaly(True), which makes autograd raise *at the exact
    # backward op* that first produces a NaN/inf, with a stack trace pointing at the forward
    # call that created it -- the direct way to localize an intermittent NaN (this run: loss=0
    # on 61/64 steps, a real finite loss+entropy on steps 5/18/19, grad_norm nan nearly always
    # -- not a deterministic math error, so comparing formulas on paper has stopped being
    # useful). Slower and more verbose, so never on by default; does not change what trains.
    if os.environ.get("SOUP_DEBUG_ANOMALY") == "1":
        import torch
        torch.autograd.set_detect_anomaly(True)
        print("[solution] SOUP_DEBUG_ANOMALY=1: torch.autograd.set_detect_anomaly(True)")
